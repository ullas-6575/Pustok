-- Payment attempts for an order. order_id is UNIQUE, so an order has one payment row: a FAILED row is
-- retried in place with a new idempotency key. idempotency_key is UNIQUE across all orders, so a key
-- that is reused for another order is rejected by the database as well as by PaymentService.
CREATE TABLE payment_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id UUID NOT NULL UNIQUE REFERENCES purchase_order(id),
    gateway VARCHAR(20) NOT NULL CHECK (gateway IN ('COD', 'MOCK', 'BKASH', 'NAGAD')),
    amount NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING', 'COMPLETED', 'FAILED')),
    idempotency_key VARCHAR(100) NOT NULL UNIQUE CHECK (btrim(idempotency_key) <> ''),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0
);
