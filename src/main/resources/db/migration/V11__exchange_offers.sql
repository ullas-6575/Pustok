-- Exchange offers on EXCHANGE listings. The offer's chat thread is exchange_conversation (V9), which is
-- unique per (listing_id, offerer_id), so an offer needs no conversation_id: the pair identifies the thread.
-- "Exchange listings only" is enforced in MarketService; a CHECK constraint cannot reference another table.
CREATE TABLE marketplace_exchange_offers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id BIGINT NOT NULL REFERENCES marketplace_resell_listings(id) ON DELETE CASCADE,
    offerer_id BIGINT NOT NULL REFERENCES identity_users(id) ON DELETE CASCADE,
    offered_title VARCHAR(255) NOT NULL CHECK (btrim(offered_title) <> ''),
    offered_author VARCHAR(255) NOT NULL CHECK (btrim(offered_author) <> ''),
    status VARCHAR(20) NOT NULL DEFAULT 'PROPOSED'
        CHECK (status IN ('PROPOSED', 'ACCEPTED', 'REJECTED', 'WITHDRAWN')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0
);

-- One live offer per offerer per listing. Settled offers (ACCEPTED, REJECTED, WITHDRAWN) are not constrained.
CREATE UNIQUE INDEX uq_exchange_offer_one_proposed
    ON marketplace_exchange_offers(listing_id, offerer_id) WHERE status = 'PROPOSED';

CREATE INDEX idx_exchange_offer_listing ON marketplace_exchange_offers(listing_id, status);
CREATE INDEX idx_exchange_offer_offerer ON marketplace_exchange_offers(offerer_id);
