CREATE TABLE purchase_order (
id UUID PRIMARY KEY, buyer_id BIGINT NOT NULL REFERENCES identity_users(id),
recipient_name VARCHAR(120) NOT NULL, phone VARCHAR(30) NOT NULL, address VARCHAR(500) NOT NULL,
total NUMERIC(18,2) NOT NULL CHECK(total>0), payment_method VARCHAR(20) NOT NULL DEFAULT 'COD' CHECK(payment_method='COD'),
status VARCHAR(20) NOT NULL DEFAULT 'PLACED', created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
request_id UUID NOT NULL, UNIQUE(buyer_id,request_id));
CREATE TABLE order_item (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id UUID NOT NULL REFERENCES purchase_order(id),
book_id BIGINT REFERENCES book(id) ON DELETE SET NULL, seller_id BIGINT NOT NULL REFERENCES identity_users(id),
title VARCHAR(255) NOT NULL, unit_price NUMERIC(12,2) NOT NULL CHECK(unit_price>0), quantity INTEGER NOT NULL CHECK(quantity>0));
CREATE INDEX idx_order_buyer ON purchase_order(buyer_id);
CREATE INDEX idx_order_item_order ON order_item(order_id);
CREATE INDEX idx_order_item_seller ON order_item(seller_id);
