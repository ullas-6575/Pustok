CREATE TABLE exchange_conversation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id BIGINT NOT NULL REFERENCES marketplace_resell_listings(id) ON DELETE CASCADE,
    owner_id BIGINT NOT NULL REFERENCES identity_users(id) ON DELETE CASCADE,
    offerer_id BIGINT NOT NULL REFERENCES identity_users(id) ON DELETE CASCADE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (listing_id, offerer_id)
);

CREATE INDEX idx_exchange_conv_owner ON exchange_conversation(owner_id);
CREATE INDEX idx_exchange_conv_offerer ON exchange_conversation(offerer_id);

CREATE TABLE exchange_chat_message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES exchange_conversation(id) ON DELETE CASCADE,
    sender_id BIGINT NOT NULL REFERENCES identity_users(id) ON DELETE CASCADE,
    content VARCHAR(1000) NOT NULL,
    sent_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_exchange_msg_conv ON exchange_chat_message(conversation_id, sent_at);
