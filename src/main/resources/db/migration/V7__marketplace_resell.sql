CREATE TABLE marketplace_resell_listings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES identity_users(id),
    listing_type VARCHAR(20) NOT NULL CHECK (listing_type IN ('RESELL', 'EXCHANGE')),
    title VARCHAR(255) NOT NULL,
    author VARCHAR(255) NOT NULL,
    book_condition VARCHAR(30) NOT NULL CHECK (book_condition IN ('LIKE_NEW', 'GOOD', 'FAIR')),
    price NUMERIC(12, 2),
    desired_book VARCHAR(255),
    description VARCHAR(500),
    status VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE' CHECK (status IN ('AVAILABLE', 'CLOSED')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_resell_user ON marketplace_resell_listings(user_id);
CREATE INDEX idx_resell_type ON marketplace_resell_listings(listing_type);
